def main(args=None):
    rclpy.init(args=args)
    node = VisionSlamNode()
    try:
        rclpy.spin(node)
    except KeyboardInterrupt:
        node.get_logger().info("Keyboard interrupt — shutting down.")
    finally:
        node.shutdown()
        node.cmd_pub.publish(Twist())
        node.destroy_node()
        cv2.destroyAllWindows()
        rclpy.shutdown()


